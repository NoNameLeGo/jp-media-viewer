/** 统一的间距刻度，取代散落各处的硬编码 dp。 */
data class Space(
    val extraSmall: Dp = 4.dp,
    val small: Dp = 8.dp,
    val medium: Dp = 12.dp,
    val large: Dp = 16.dp,
    val extraLarge: Dp = 24.dp,
)

val MaterialTheme.spaces: Space
    @Composable get() = Space()

@Composable
fun JpMediaViewerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // 动态取色在 Android 12+ 可用；低版本回退到自定义色板。
    dynamicColor: Boolean = true,
    pureBlack: Boolean = false,
    content: @Composable () -> Unit,
) {
    val baseColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val colorScheme = if (darkTheme && pureBlack) baseColorScheme.pureBlack() else baseColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}

/** 纯黑沉浸：把底层表面压成纯黑，适合 OLED 全屏浏览。 */
private fun ColorScheme.pureBlack() = copy(
    background = Color.Black,
    surface = Color.Black,
    surfaceContainerLowest = Color.Black,
)
